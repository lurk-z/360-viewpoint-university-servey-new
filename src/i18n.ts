export type MessageKey = keyof (typeof messages)['th'];

export function message(locale: Locale, key: MessageKey): string {
  return messages[locale][key];
}

export function sceneCounter(locale: Locale, current: number, total: number): string {
  return locale === 'th' ? `ฉากที่ ${current} จาก ${total}` : `Scene ${current} of ${total}`;
}

export function imageCounter(locale: Locale, current: number, total: number): string {
  return locale === 'th' ? `รูปที่ ${current} จาก ${total}` : `Image ${current} of ${total}`;
}

export function goToScene(locale: Locale, title: string): string {
  return locale === 'th' ? `ไปยัง ${title}` : `Go to ${title}`;
}

export function currentScene(locale: Locale, title: string): string {
  return locale === 'th' ? `ฉากปัจจุบัน: ${title}` : `Current scene: ${title}`;
}

export function sceneChanged(locale: Locale, current: number, total: number, title: string): string {
  return locale === 'th'
    ? `เปลี่ยนเป็นฉาก ${current} จาก ${total}: ${title}`
    : `Changed to scene ${current} of ${total}: ${title}`;
}

export function loadingProgress(locale: Locale, progress: number): string {
  return locale === 'th' ? `กำลังโหลด ${progress}%` : `Loading ${progress}%`;
}
